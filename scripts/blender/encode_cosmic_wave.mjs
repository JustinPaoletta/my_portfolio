/** Encode the Blender-rendered wave once, holding the final lowered-arm pose. */
import sharp from 'sharp';
import { Buffer } from 'node:buffer';
import process from 'node:process';
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
const manifest = JSON.parse(
  await readFile(
    'output/playwright/cosmic-astronaut/render-manifest.json',
    'utf8'
  )
);
const sourceHash = createHash('sha256')
  .update(await readFile('assets/blender/cosmic-astronaut.blend'))
  .digest('hex');
if (sourceHash !== manifest.source_sha256)
  throw new Error('Render frames do not match the saved Blender source.');
const folder = 'output/playwright/cosmic-astronaut/wave-frames';
const files = (await readdir(folder))
  .filter((file) => /^\d{4}\.png$/.test(file))
  .sort();
if (files.length !== manifest.frames)
  throw new Error(`Expected ${manifest.frames} frames; got ${files.length}`);
if (
  files.some(
    (file, index) => file !== `${String(index + 1).padStart(4, '0')}.png`
  )
)
  throw new Error('Render frames are not contiguous.');
const width = manifest.width;
const pageHeight = manifest.height;
const frames = [];
for (const file of files) {
  const pixels = await sharp(`${folder}/${file}`)
    .ensureAlpha()
    .raw()
    .toBuffer();
  if (pixels.length !== width * pageHeight * 4)
    throw new Error(`Wrong frame dimensions: ${file}`);
  frames.push(pixels);
}
await sharp(Buffer.concat(frames), {
  raw: { width, height: pageHeight * frames.length, channels: 4, pageHeight },
})
  .webp({
    quality: 86,
    alphaQuality: 100,
    effort: 5,
    loop: 1,
    delay: Array(frames.length).fill(1000 / manifest.fps),
  })
  .toFile('public/images/hero/cosmic/astronaut-wave.webp');
await sharp('output/playwright/cosmic-astronaut/beauty.png')
  .resize({ width: 720 })
  .webp({ quality: 90, alphaQuality: 100, effort: 6 })
  .toFile('public/images/hero/cosmic/astronaut-asteroid.webp');
process.stdout.write(
  JSON.stringify(
    await sharp('public/images/hero/cosmic/astronaut-wave.webp', {
      animated: true,
    }).metadata()
  ) + '\n'
);

const versionedAssets = [];
for (const [name, file] of [
  ['COSMIC_ASTRONAUT_POSTER', 'astronaut-asteroid.webp'],
  ['COSMIC_ASTRONAUT_ANIMATION', 'astronaut-wave.webp'],
]) {
  const hash = createHash('sha256')
    .update(await readFile(`public/images/hero/cosmic/${file}`))
    .digest('hex')
    .slice(0, 16);
  versionedAssets.push(
    `export const ${name} =\n  '/images/hero/cosmic/${file}?v=${hash}';`
  );
}
await writeFile(
  'src/config/cosmicAstronautAssets.ts',
  '// Generated by scripts/blender/encode_cosmic_wave.mjs.\n' +
    versionedAssets.join('\n') +
    '\n'
);
